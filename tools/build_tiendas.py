#!/usr/bin/env python3
"""Writes the store list into the HTML so crawlers (and AI assistants, which don't run JavaScript) can read it.

- site/donde-comprar.html: the town-grouped list inside #results (between the tiendas:start/end markers),
  The page's JavaScript replaces this with the live list from the sheet as soon as it loads, so what people
  see is unchanged; this is only the starting HTML.
- site/index.html: the "Disponible en" names, the "N lugares en N pueblos" line and the TIENDAS backup list
  in donde-comprar.html, all from the same sheet (CSV in STORES_CSV_URL; backup = TIENDAS if unreachable).
Run after the stores change (the recipes workflow runs it every 15 min).
"""
import datetime as dt, html, json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
from build_llms import stores

MESES = ['enero', 'febrero', 'marzo', 'abril', 'mayo', 'junio', 'julio', 'agosto', 'septiembre', 'octubre', 'noviembre', 'diciembre']
KIND = lambda t: 'tienda' if re.search(r'tienda|cash|licorer|colmado|supermercado', t.lower()) else ('rest' if re.search(r'restaurante|hotel|taquer', t.lower()) else 'bar')
COLOR = {'tienda': ('var(--amarillo)', 'var(--negro)'), 'rest': ('var(--naranja)', 'var(--negro)'), 'bar': ('var(--rojo)', 'var(--crema)')}
LBL = {'tienda': 'Tienda', 'rest': 'Restaurante', 'bar': 'Bar'}


def type_label(t):
    k = KIND(t); base = LBL[k]; raw = t.strip()
    if not raw or raw.lower() == base.lower():
        return base
    rest = re.sub(r'^' + base + r'(s)?\s*(y|&)?\s*', '', raw, flags=re.I).strip()
    rest = re.sub(r'\s*(y|&)\s*' + base + r'$', '', rest, flags=re.I).strip()
    return f'{base} · {rest[:1].upper()}{rest[1:]}' if rest and rest.lower() != base.lower() else base


def main():
    rows = stores()
    ZONA = {'condado / miramar': 'San Juan', 'santurce': 'San Juan', 'viejo san juan': 'San Juan', 'hato rey': 'San Juan', 'río piedras': 'San Juan'}  # same as the page script
    pueblos, nombres = [], {}
    for n, t, d, p in rows:
        town = ZONA.get(p.strip().lower(), p)
        if town not in pueblos: pueblos.append(town)
        nombres[n] = nombres.get(n, 0) + 1
    hoy = dt.date.today(); fecha = f'{hoy.day} de {MESES[hoy.month - 1]} de {hoy.year}'
    e = html.escape

    # ---- donde-comprar.html
    p = os.path.join(ROOT, 'site/donde-comprar.html'); s = open(p, encoding='utf8').read()
    g = {}
    for n, t, d, pb in rows: g.setdefault(pb, []).append((n, t, d, pb))
    import locale
    out = []
    for pb in sorted(g, key=lambda x: x.lower()):
        items = ''
        for i, (n, t, d, _) in enumerate(g[pb]):
            c, f = COLOR[KIND(t)]
            q = html.escape(f'{n}, {d}, {pb}, Puerto Rico'.replace(' ', '+'))
            items += (f'<div class="store"><span class="dot" style="background:{c};color:{f}"></span><span class="store-name">{e(n)}</span>'
                      f'<span class="store-addr">{e(type_label(t))} · {e((d + ", ") if d else "")}{e(pb)}</span>'
                      f'<div class="go" style="grid-column:2"><a class="primary" href="https://www.google.com/maps/search/?api=1&amp;query={q}" target="_blank" rel="noopener">Cómo llegar →</a></div></div>')
        out.append(f'<div class="pueblo"><h3>{e(pb)}<small>{len(g[pb])} {"lugar" if len(g[pb]) == 1 else "lugares"}</small></h3>{items}</div>')
    lead = ''  # no visible lead or date line (Alfonso, Nov 1): the list itself is the point
    block = f'<!-- tiendas:start (GENERATED by tools/build_tiendas.py; the page script replaces it with the live list) -->{lead}{"".join(out)}<!-- tiendas:end -->'
    if '<!-- tiendas:start' in s:
        s = re.sub(r'<!-- tiendas:start.*?<!-- tiendas:end -->', lambda m: block, s, flags=re.S)
    else:
        # replace only the skeleton (<div class="sk-list">...</div>), keeping the </div> that closes #results
        s = re.sub(r'(<div class="results" id="results" aria-live="polite">)<div class="sk-list".*?</div></div>(</div>\s*<section class="sell")', lambda m: m.group(1) + block + m.group(2), s, count=1, flags=re.S)
        assert 'tiendas:start' in s, 'no encontré el skeleton de #results'
    # TIENDAS backup array, from the same rows
    js = ',\n'.join(f'  {json.dumps([n, t, d, pb, "", ""], ensure_ascii=False)}' for n, t, d, pb in rows)
    # keep coordinates that already exist in the backup for the same store
    m = re.search(r'const TIENDAS\s*=\s*\[(.*?)\];', s, re.S)
    old = {(r[0], r[3]): r for r in json.loads('[' + m.group(1) + ']')}
    arr = []
    for n, t, d, pb in rows:
        o = old.get((n, pb)); arr.append([n, t, d, pb, o[4] if o else '', o[5] if o else ''])
    js = ',\n'.join('  ' + json.dumps(r, ensure_ascii=False) for r in arr)
    s = s[:m.start(1)] + '\n' + js + '\n' + s[m.end(1):]
    open(p, 'w', encoding='utf8').write(s)

    # ---- index.html: "Disponible en" names (top 5 by locations) and the count line
    p = os.path.join(ROOT, 'site/index.html'); s = open(p, encoding='utf8').read()
    top = sorted(nombres, key=lambda n: (-nombres[n], rows.index(next(r for r in rows if r[0] == n))))[:5]
    s = re.sub(r'<ul class="proof-list">.*?</ul>', '<ul class="proof-list">' + ''.join(f'<li>{e(n)}</li>' for n in top) + '</ul>', s, count=1, flags=re.S)
    s = re.sub(r'<b class="hl">\d+ lugares en \d+ pueblos\.</b>', f'<b class="hl">{len(rows)} lugares en {len(pueblos)} pueblos.</b>', s, count=1)
    open(p, 'w', encoding='utf8').write(s)
    print(f'tiendas: {len(rows)} lugares, {len(pueblos)} pueblos, lista del {fecha}')


if __name__ == '__main__':
    main()
